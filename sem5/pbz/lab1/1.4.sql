SELECT DISTINCT
    t1.Фамилия,
    t4.Кодовый_номер_предмета,
	t2.Название_предмета
FROM Преподаватель AS t1
JOIN Преподаватель_преподает_предметы_в_группах AS t4
ON t1.Личный_номер = t4.Личный_номер
JOIN Предмет AS t2
ON t4.Кодовый_номер_предмета = t2.Кодовый_номер_предмета
WHERE t1.Фамилия = 'Костин'