SELECT DISTINCT
    t4.Номер_аудитории,
    t2.Название_предмета,
	t3.Название_группы
FROM Преподаватель_преподает_предметы_в_группах AS t4
JOIN Предмет AS t2
ON t4.Кодовый_номер_предмета = t2.Кодовый_номер_предмета
JOIN Студенческая_группа AS t3
ON t4.Кодовый_номер_группы = t3.Кодовый_номер_группы
WHERE t4.Номер_аудитории BETWEEN 100 AND 200